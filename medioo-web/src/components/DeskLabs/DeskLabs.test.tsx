import { cleanup, render, within } from "@testing-library/react";
import { afterEach, describe, expect, it } from "vitest";
import type { LabsJson } from "@/api/types";
import { t, type Lang } from "@/copy";
import { paperDate } from "@/components/LabList/LabList";
import { CHIP_KEY, chipKindOf } from "@/components/StatusChip/StatusChip";
import bp from "../../../fixtures/api/health/bp-flagged.json";
import none from "../../../fixtures/api/health/labs-none.json";
import nonNumeric from "../../../fixtures/api/health/labs-non-numeric.json";
import printedRange from "../../../fixtures/api/health/labs-printed-range.json";
import some from "../../../fixtures/api/health/labs-some.json";
import twoUnits from "../../../fixtures/api/health/labs-two-units.json";
import withUnknown from "../../../fixtures/api/health/labs-with-unknown.json";
import { DeskLabs, boundText, chosenLab, type DeskLabsProps } from "./DeskLabs";

/*
 * The lab values on the desktop layout (plan desktop-parity Phase 2, row L1; desktop.html `labsView()`): every value
 * listed on the left, in Java's order; the chosen one on the right with its newest reading as a figure, its chip, its
 * date and the range its paper printed, then "over time" and each reading as written on its paper, each a way to that
 * paper. Java's fixtures, generated by HealthApiContractTest.
 */

afterEach(cleanup);

const SOME = some.body as LabsJson;
const WITH_UNKNOWN = withUnknown.body as LabsJson;
const NON_NUMERIC = nonNumeric.body as LabsJson;
const PRINTED = printedRange.body as LabsJson;
const TWO_UNITS = twoUnits.body as LabsJson;
const BP = bp.body as LabsJson;
const NONE = none.body as LabsJson;

const at = (lab: string) => `/at?lab=${lab}`;
const open = (id: string) => `/open/${id}`;

function labs(body: LabsJson, extra: Partial<DeskLabsProps> = {}) {
  return render(<DeskLabs lang="bn" labs={body} asked={null} at={at} soft={false} open={open} send="/send" {...extra} />);
}

const rows = (c: HTMLElement) => [...c.querySelectorAll<HTMLAnchorElement>("[data-lab]")];
const detail = (c: HTMLElement) => c.querySelector<HTMLElement>(".desk-labs__detail")!;
const newest = (body: LabsJson, i: number) => body.series[i]!.points[0]!;

describe("DeskLabs", () => {
  it("theChosenValueIsTheAskedOneElseTheFirst", () => {
    const creatinine = SOME.series[0]!;
    expect(chosenLab(SOME, creatinine.points[0]!.observation_id), "its newest reading").toBe(creatinine.points[0]!.observation_id);
    // A link made before a newer paper arrived names an older reading: it still opens that value.
    expect(chosenLab(SOME, creatinine.points[2]!.observation_id), "an older reading of it").toBe(creatinine.points[0]!.observation_id);
    expect(chosenLab(SOME, newest(SOME, 2).observation_id)).toBe(newest(SOME, 2).observation_id);
    expect(chosenLab(SOME, "junk"), "nothing it knows: the first").toBe(newest(SOME, 0).observation_id);
    expect(chosenLab(SOME, null)).toBe(newest(SOME, 0).observation_id);
    expect(chosenLab(SOME, "bp"), "no blood pressure here: the first").toBe(newest(SOME, 0).observation_id);
    expect(chosenLab(BP, null), "only blood pressure").toBe("bp");
    expect(chosenLab(BP, "bp")).toBe("bp");
    expect(chosenLab(NONE, null), "nothing read").toBeNull();
  });

  it("everyValueIsARowInJavasOrderEachLinkingToItself", () => {
    const { container } = labs(SOME);
    const list = container.querySelector<HTMLElement>(`[aria-label="${t("bn", "desk.labs.list")}"]`)!;
    expect(within(list).getByRole("heading", { level: 1 }).textContent).toBe(t("bn", "desk.nav.labs"));
    expect(rows(container).map((r) => r.dataset.lab)).toEqual(SOME.series.map((s) => s.points[0]!.observation_id));
    rows(container).forEach((row, i) => {
      const s = SOME.series[i]!;
      const p = s.points[0]!;
      expect(row.getAttribute("href")).toBe(at(p.observation_id));
      expect(row.textContent).toContain(s.name);
      expect(row.textContent).toContain(p.value);
      expect(row.textContent).toContain(s.unit!);
      expect(row.textContent, "its chip's word").toContain(t("bn", CHIP_KEY[chipKindOf(p.kind, p.side)]));
      expect(row.textContent, "its newest paper's date").toContain(paperDate("bn", p));
      // desktop.html's desk.labs.papers ("{n} papers") only when the value is on more than one paper, the count in Bangla digits.
      const count = t("bn", "desk.labs.papers", s.points.length);
      if (s.points.length > 1) expect(row.textContent).toContain(count);
      else expect(row.textContent).not.toContain(count);
    });
  });

  it("theChosenRowIsCurrentAndTheDetailIsItsNewestReading", () => {
    const creatinine = SOME.series[0]!;
    const { container } = labs(SOME, { asked: creatinine.points[0]!.observation_id });
    expect(rows(container).filter((r) => r.getAttribute("aria-current") === "true").map((r) => r.dataset.lab)).toEqual([
      creatinine.points[0]!.observation_id,
    ]);
    const d = detail(container);
    expect(within(d).getByRole("heading", { level: 2 }).textContent).toBe(`${creatinine.name} ${creatinine.unit}`);
    expect(d.getAttribute("aria-labelledby")).toBe(within(d).getByRole("heading", { level: 2 }).id);
    const figure = d.querySelector<HTMLElement>(".desk-labs__figure")!;
    expect(figure.textContent).toBe(`${creatinine.points[0]!.value}${creatinine.unit}`);
    const sub = d.querySelector<HTMLElement>(".desk-labs__sub")!;
    expect(sub.textContent).toContain(t("bn", CHIP_KEY["out-high"]));
    expect(sub.textContent).toContain(t("bn", "desk.labs.latest", paperDate("bn", creatinine.points[0]!)));
    expect(sub.textContent).toContain(t("bn", "value.range", "59", "104"));
  });

  it("theRangeKeepsThePapersDigitsAndIsWrittenOnlyFromJavasNumbers", () => {
    // labs-with-unknown: HbA1c's paper printed "4.0–5.6", Java sends 4 and 5.6: the paper's 4.0 is written.
    const hba1c = labs(WITH_UNKNOWN).container;
    expect(detail(hba1c).querySelector(".desk-labs__sub")!.textContent).toContain(t("bn", "value.range", "4.0", "5.6"));
    cleanup();
    // labs-printed-range: potassium is critical with no number Java keeps (ref_low/high null) though ref_text says
    // 3.5–5.1: no range is written, never one read off ref_text.
    const potassium = PRINTED.series.find((s) => s.canonical_name === "potassium")!;
    const c = labs(PRINTED, { asked: potassium.points[0]!.observation_id }).container;
    const sub = detail(c).querySelector<HTMLElement>(".desk-labs__sub")!;
    expect(sub.textContent).not.toContain("3.5");
    expect(sub.textContent).not.toContain(t("bn", "value.range.none"));
    expect(sub.textContent).toContain(t("bn", "desk.labs.latest", paperDate("bn", potassium.points[0]!)));
  });

  it("aBoundIsThePapersOwnDigitsOnlyWhenTheyAreTheSameNumber", () => {
    expect(boundText(4, "4.0–5.6")).toBe("4.0");
    expect(boundText(5.6, "4.0–5.6")).toBe("5.6");
    // The dangerous direction: a printed number that only looks alike is never taken for the bound.
    expect(boundText(4, "40–56"), "40 is not 4").toBe("4");
    expect(boundText(0.5, "5"), "5 is not 0.5").toBe("0.5");
    expect(boundText(104, null)).toBe("104");
    expect(boundText(104, "")).toBe("104");
  });

  it("overTimeIsTheChartForPlainNumbersOneReadingsSentenceOrTheReadingsAsWritten", () => {
    // Three plain readings: TrendChart, and desktop.html's line under it.
    let d = detail(labs(SOME).container);
    const over = d.querySelector<HTMLElement>("[data-panel=over-time]")!;
    expect(within(over).getByRole("heading", { level: 3 }).textContent).toBe(t("bn", "desk.labs.over_time"));
    expect(over.querySelector(".trend-chart")).not.toBeNull();
    expect(over.textContent).toContain(t("bn", "desk.labs.foot"));
    cleanup();
    // One reading: desktop.html's sentence, no chart and no line about dots.
    d = detail(labs(SOME, { asked: newest(SOME, 1).observation_id }).container);
    const once = d.querySelector<HTMLElement>("[data-panel=over-time]")!;
    expect(once.textContent).toContain(t("bn", "desk.labs.once"));
    expect(once.querySelector(".trend-chart")).toBeNull();
    expect(once.textContent).not.toContain(t("bn", "desk.labs.foot"));
    cleanup();
    // ">500" is not a plain number: every reading as written, each with its chip, and nothing drawn.
    const creatinine = NON_NUMERIC.series[0]!;
    d = detail(labs(NON_NUMERIC).container);
    const written = d.querySelector<HTMLElement>("[data-panel=over-time]")!;
    expect(written.querySelector(".trend-chart")).toBeNull();
    expect(written.textContent).not.toContain(t("bn", "desk.labs.foot"));
    const readings = [...written.querySelectorAll<HTMLElement>("[data-reading-for]")];
    expect(readings.map((r) => r.dataset.readingFor)).toEqual(creatinine.points.map((p) => p.observation_id));
    readings.forEach((r, i) => {
      const p = creatinine.points[i]!;
      expect(r.textContent).toContain(p.value);
      expect(r.textContent).toContain(t("bn", CHIP_KEY[chipKindOf(p.kind, p.side)]));
    });
  });

  it("eachReadingAsWrittenIsItsOwnCropAndTheWayToItsPaper", () => {
    const creatinine = SOME.series[0]!;
    const d = detail(labs(SOME).container);
    const written = d.querySelector<HTMLElement>("[data-panel=as-written]")!;
    expect(within(written).getByRole("heading", { level: 3 }).textContent).toBe(t("bn", "desk.labs.as_written"));
    const links = [...written.querySelectorAll<HTMLAnchorElement>("a[data-observation]")];
    // Newest first, as Java sent them; each its own reading's crop (matched by id, never by position alone).
    expect(links.map((a) => a.dataset.observation)).toEqual(creatinine.points.map((p) => p.observation_id));
    for (const a of links) {
      const p = creatinine.points.find((x) => x.observation_id === a.dataset.observation)!;
      expect(a.getAttribute("href")).toBe(open(p.document_id));
      const img = a.querySelector("img")!;
      expect(img.getAttribute("src")).toBe(p.crop.src);
      expect(img.getAttribute("alt")).toBe(t("bn", "health.crop.alt"));
      expect(a.textContent).toContain(paperDate("bn", p));
    }
  });

  it("oneNameInTwoUnitsIsTwoValuesEachNamedWithItsUnit", () => {
    const [mmol, mgdl] = TWO_UNITS.series;
    const { container } = labs(TWO_UNITS, { asked: mgdl!.points[0]!.observation_id });
    expect(rows(container)).toHaveLength(2);
    expect(rows(container)[0]!.textContent).toContain(mmol!.unit!);
    expect(rows(container)[1]!.textContent).toContain(mgdl!.unit!);
    expect(within(detail(container)).getByRole("heading", { level: 2 }).textContent).toBe(`${mgdl!.name} ${mgdl!.unit}`);
    expect(detail(container).querySelector(".desk-labs__figure")!.textContent).toBe(`${mgdl!.points[0]!.value}${mgdl!.unit}`);
  });

  it("bloodPressureIsOneValueEachHalfWithItsOwnChipAndCrop", () => {
    const pair = BP.bp.points[0]!;
    const { container } = labs(BP);
    const row = rows(container).find((r) => r.dataset.lab === "bp")!;
    expect(row.getAttribute("href")).toBe(at("bp"));
    expect(row.textContent).toContain(t("bn", "health.bp"));
    expect(row.textContent).toContain(`${pair.systolic.value}/${pair.diastolic.value}`);
    const d = detail(container);
    expect(within(d).getByRole("heading", { level: 2 }).textContent).toBe(t("bn", "health.bp"));
    expect(d.querySelector(".desk-labs__figure")!.textContent).toBe(`${pair.systolic.value}/${pair.diastolic.value}`);
    // Each half is its own group: its value beside its own chip, never the other half's (bp-flagged: 130 is out of
    // range, 80 inside).
    for (const half of [pair.systolic, pair.diastolic]) {
      const group = d.querySelector<HTMLElement>(`[data-panel=over-time] [data-observation-id="${half.observation_id}"]`)!;
      expect(group.textContent).toContain(half.value);
      expect(group.textContent).toContain(t("bn", CHIP_KEY[chipKindOf(half.kind, half.side)]));
    }
    const link = d.querySelector<HTMLAnchorElement>("[data-panel=as-written] a")!;
    expect(link.getAttribute("href")).toBe(open(pair.document_id));
    expect([...link.querySelectorAll("img")].map((i) => i.getAttribute("src"))).toEqual([pair.systolic.crop.src, pair.diastolic.crop.src]);
  });

  it("nothingReadYetSaysSoAndOffersToSendAPaper", () => {
    const { container } = labs(NONE);
    expect(rows(container)).toHaveLength(0);
    expect(detail(container)).toBeNull();
    expect(within(container).getByRole("heading", { level: 1 }).textContent, "the screen's heading").toBe(t("bn", "desk.nav.labs"));
    expect(within(container).getByRole("heading", { level: 2 }).textContent).toBe(t("bn", "health.labs.none"));
    expect(container.textContent).toContain(t("bn", "desk.labs.none.more"));
    expect(within(container).getByRole("link", { name: t("bn", "desk.attach") }).getAttribute("href")).toBe("/send");
    cleanup();
    // Where no page takes a paper for this viewer, no link to one.
    const quiet = labs(NONE, { send: null }).container;
    expect(within(quiet).queryByRole("link")).toBeNull();
  });

  it.each<Lang>(["bn", "en"])("everyWordIsTheBundles (%s)", (lang) => {
    const { container } = labs(SOME, { lang });
    expect(container.textContent).toContain(t(lang, "desk.nav.labs"));
    expect(container.textContent).toContain(t(lang, "desk.labs.over_time"));
    expect(container.textContent).toContain(t(lang, "desk.labs.as_written"));
  });
});
