import { cleanup, render, within } from "@testing-library/react";
import { afterEach, describe, expect, it } from "vitest";
import type { MedicinesJson } from "@/api/types";
import { t, type CopyKey, type Lang } from "@/copy";
import { paperDate } from "@/components/LabList/LabList";
import emptyLatest from "../../../fixtures/api/health/medicines-empty-latest.json";
import latest from "../../../fixtures/api/health/medicines-latest.json";
import newerUnread from "../../../fixtures/api/health/medicines-newer-unread.json";
import noneNewerUnread from "../../../fixtures/api/health/medicines-none-newer-unread.json";
import none from "../../../fixtures/api/health/medicines-none.json";
import protoAmma from "../../../fixtures/api/health/proto-medicines-amma.json";
import { DeskMedicines, type DeskMedicinesProps } from "./DeskMedicines";

/*
 * The medicines on the desktop layout (plan desktop-parity Phase 2, row M1; desktop.html `medsView()`): the newest
 * prescription under Java's heading and its date, each line its own crop, the line as written and the way to the paper;
 * the pharmacy and doctor lines under them. Java's fixtures, generated by HealthApiContractTest and ProtoFamilyContractTest.
 */

afterEach(cleanup);

const LATEST = latest.body as MedicinesJson;
const PROTO = protoAmma.body as MedicinesJson;
const open = (id: string) => `/open/${id}`;
/** The mother's name made possessive, as me/proto.json gives it (escaped: no Bangla in source). */
const AMMAR = "\u0986\u09AE\u09CD\u09AE\u09BE\u09B0";

function meds(body: MedicinesJson, extra: Partial<DeskMedicinesProps> = {}) {
  return render(<DeskMedicines lang="bn" possessive={AMMAR} medicines={body} open={open} {...extra} />);
}

const cards = (c: HTMLElement) => [...c.querySelectorAll<HTMLElement>("[data-medicine]")];

describe("DeskMedicines", () => {
  it("theScreenIsNamedForThePatientAndSaysWhatItHolds", () => {
    const { container } = meds(PROTO);
    expect(within(container).getByRole("heading", { level: 1 }).textContent).toBe(t("bn", "desk.nav.meds"));
    expect(within(container).getByRole("heading", { level: 2 }).textContent).toBe(t("bn", "desk.meds.title", AMMAR));
    expect(container.textContent).toContain(t("bn", "desk.meds.lede"));
  });

  it("theNewestPrescriptionIsUnderJavasHeadingWithItsDate", () => {
    const { container } = meds(LATEST);
    const head = container.querySelector<HTMLElement>(".desk-meds__head")!;
    expect(head.textContent).toContain(t("bn", LATEST.heading_key as CopyKey));
    // medicines-latest's date is one the model was unsure of: said so, as the phone says it.
    expect(head.textContent).toContain(
      paperDate("bn", { date: LATEST.date!, date_is_upload_day: LATEST.date_is_upload_day === true, date_uncertain: LATEST.date_uncertain === true }),
    );
  });

  it("eachLineIsItsOwnCropItsWrittenFieldsAndTheWayToThePaper", () => {
    const { container } = meds(PROTO);
    expect(cards(container)).toHaveLength(PROTO.medicines.length);
    cards(container).forEach((card, i) => {
      const line = PROTO.medicines[i]!;
      // Its own crop, in Java's order: matched by the crop's own address, never by position alone.
      expect(card.querySelector("img")!.getAttribute("src")).toBe(line.crop.src);
      expect(card.dataset.medicine).toBe(line.crop.src);
      // Every field the line was written with, each Java's string as sent (the paper's own Bangla digits stay as printed).
      const written = Object.fromEntries([...card.querySelectorAll<HTMLElement>("[data-field]")].map((f) => [f.dataset.field, f.textContent]));
      const sent = Object.fromEntries(Object.entries(line).filter(([k]) => k !== "crop"));
      expect(written).toEqual(sent);
      expect(card.textContent).toContain(t("bn", "desk.meds.as_written"));
      const link = within(card).getByRole("link", { name: t("bn", "desk.meds.paper") });
      expect(link.getAttribute("href")).toBe(open(PROTO.document_id!));
    });
  });

  it("aLineWithOnlySomeFieldsShowsOnlyThose", () => {
    const { container } = meds(LATEST);
    const second = cards(container)[1]!;
    expect([...second.querySelectorAll<HTMLElement>("[data-field]")].map((f) => f.dataset.field)).toEqual(["name", "dose_text"]);
  });

  it("thePharmacyAndDoctorLinesFollowTheMedicines", () => {
    const { container } = meds(LATEST);
    const foot = container.querySelector<HTMLElement>(".desk-meds__foot")!;
    expect(foot.textContent).toContain(t("bn", "med.pharmacy"));
    expect(foot.textContent).toContain(t("bn", "health.medicines.doctor_only"));
  });

  it("anEmptyNewestPrescriptionIsItsDateAndNothingOlder", () => {
    const body = emptyLatest.body as MedicinesJson;
    const { container } = meds(body);
    expect(cards(container)).toHaveLength(0);
    expect(container.querySelector(".desk-meds__head")!.textContent).toContain(t("bn", body.heading_key as CopyKey));
    expect(container.querySelector(".desk-meds__foot")).toBeNull();
  });

  it("aNewerPrescriptionStillBeingReadIsSaidAndLinked", () => {
    const body = newerUnread.body as MedicinesJson;
    const { container } = meds(body);
    const link = within(container).getByRole("link", { name: t("bn", "health.medicines.newer_unread") });
    expect(link.getAttribute("href")).toBe(open(body.newer_document_id!));
    expect(cards(container)).toHaveLength(body.medicines.length);
  });

  it("noPrescriptionYetSaysSoAndAFirstBeingReadIsLinked", () => {
    let c = meds(none.body as MedicinesJson).container;
    expect(c.textContent).toContain(t("bn", "desk.meds.none"));
    expect(cards(c)).toHaveLength(0);
    cleanup();
    const body = noneNewerUnread.body as MedicinesJson;
    c = meds(body).container;
    expect(within(c).getByRole("link", { name: t("bn", "health.medicines.first_unread") }).getAttribute("href")).toBe(open(body.newer_document_id!));
    expect(c.textContent).not.toContain(t("bn", "desk.meds.none"));
  });

  it("nothingHereJudgesAMedicine", () => {
    // No chip, no colour, no status: Medioo says nothing about a medicine (W9, DR-45 item 7).
    const { container } = meds(PROTO);
    expect(container.querySelector(".status-chip, .urgency-tag, [data-urgency]")).toBeNull();
  });

  it.each<Lang>(["bn", "en"])("everyWordIsTheBundles (%s)", (lang) => {
    const { container } = meds(PROTO, { lang, possessive: "Ma's" });
    expect(container.textContent).toContain(t(lang, "desk.meds.title", "Ma's"));
    expect(container.textContent).toContain(t(lang, "desk.meds.paper"));
  });
});
