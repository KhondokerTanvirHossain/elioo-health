import { cleanup, render, within } from "@testing-library/react";
import { afterEach, describe, expect, it } from "vitest";
import type { CalendarJson } from "@/api/types";
import { banglaDigits, formatDate, formatDayMonth, formatMonth, formatMonthYear, t, type CopyKey, type Lang } from "@/copy";
import busy from "../../../fixtures/api/calendar/busy.json";
import empty from "../../../fixtures/api/calendar/empty.json";
import fortyFive from "../../../fixtures/api/calendar/forty-five.json";
import { DeskCalendar, chosenDay, type DeskCalendarProps } from "./DeskCalendar";

/*
 * The desktop calendar (plan desktop-parity Phase 2, row C1; desktop.html `calView()`): the month across the content
 * region, each day a link naming its papers by urgency, today filled, the chosen day marked, a doctor's day ringed; the
 * chosen day's papers and doctor's dates in the panel on the right, each with the way to the paper and its
 * conversation; the month and list views and ‹ today › in the toolbar. Java's fixtures, generated by PatientTimelineApiContractTest.
 */

afterEach(cleanup);

const BUSY = busy.body as CalendarJson;
const FORTY_FIVE = fortyFive.body as CalendarJson;
const EMPTY = empty.body as CalendarJson;
const NOW_LAB = BUSY.days[0]!.papers[0]!;
const FOLLOW = BUSY.days[1]!.follow_ups[0]!;

/** The screen's address for a month, a day and a view, as a page builds it; easy to read back in a test. */
const at: DeskCalendarProps["at"] = ({ month, day, view }) =>
  `/at?${new URLSearchParams(Object.entries({ month, day, view }).filter((e): e is [string, string] => typeof e[1] === "string")).toString()}`;
const open = (id: string) => `/open/${id}`;
/** desktop.html's promise of a WhatsApp reminder the evening before (`calView()`), held as the words' own stem. */
const REMINDER = "\u09AE\u09A8\u09C7 \u0995\u09B0\u09BF\u09AF\u09BC\u09C7"; // "remind" (mone koriye), escaped: no Bangla in source

function calendar(extra: Partial<DeskCalendarProps> = {}) {
  return render(
    <DeskCalendar
      lang="bn"
      view="month"
      calendar={BUSY}
      today="2026-10-20"
      asked={null}
      before="2026-09"
      after="2026-11"
      at={at}
      soft={false}
      open={open}
      list={<p data-slot="list">list</p>}
      {...extra}
    />,
  );
}

const cell = (c: HTMLElement, date: string) => c.querySelector<HTMLElement>(`[data-date="${date}"]`)!;
const panel = (c: HTMLElement) => c.querySelector<HTMLElement>("aside")!;

describe("DeskCalendar", () => {
  it("theChosenDayIsTheAskedOneElseTodayElseTheLatestWithSomething", () => {
    expect(chosenDay(BUSY, "2026-10-20", "2026-10-15"), "asked, inside the month").toBe("2026-10-15");
    expect(chosenDay(BUSY, "2026-10-20", "2026-11-03"), "asked outside the month: today").toBe("2026-10-20");
    expect(chosenDay(BUSY, "2026-10-20", "2026-10-32"), "not a day of the month: today").toBe("2026-10-20");
    expect(chosenDay(BUSY, "2026-10-20", "junk"), "not a date: today").toBe("2026-10-20");
    expect(chosenDay(BUSY, "2026-12-01", null), "today in another month: the month's latest day with something").toBe("2026-10-31");
    expect(chosenDay(EMPTY, "2026-12-01", null), "nothing in the month: its first day").toBe(`${EMPTY.month}-01`);
  });

  it("theMonthIsSaturdayFirstAndEachDayIsALinkToThatDay", () => {
    const { container } = calendar();
    const heads = [...container.querySelectorAll("thead th")].map((th) => th.textContent);
    // Saturday first, Friday last; Thursday in full, as desktop.html heads it.
    const keys = ["sat", "sun", "mon", "tue", "wed"].map((d) => t("bn", `calendar.weekday.${d}` as CopyKey));
    expect(heads).toEqual([...keys, t("bn", "desk.cal.thu"), t("bn", "calendar.weekday.fri")]);
    const days = container.querySelectorAll<HTMLAnchorElement>("td a[data-date]");
    expect(days, "every day of October").toHaveLength(31);
    // 1 October 2026 is a Thursday: the sixth column, after five blank cells.
    const first = container.querySelector("tbody tr")!.querySelectorAll("td");
    expect([...first].findIndex((td) => td.querySelector("a") !== null)).toBe(5);
    // The weeks end with the month: the cells after the 31st are not drawn as days (desktop.html stops at the 31st).
    const last = [...container.querySelectorAll("tbody tr")].at(-1)!.querySelectorAll("td");
    expect([...last].map((td) => td.className)).toEqual([
      "desk-cal__cell",
      ...Array<string>(6).fill("desk-cal__cell desk-cal__cell--after"),
    ]);
    expect([...first].slice(0, 5).every((td) => td.classList.contains("desk-cal__cell--before"))).toBe(true);
    expect(cell(container, "2026-10-15").getAttribute("href")).toBe(at({ month: "2026-10", day: "2026-10-15", view: "month" }));
    // The day says itself in the phone calendar's words: its date, its papers, its doctor's dates.
    expect(cell(container, "2026-10-01").hasAttribute("aria-label"), "named by its own text (WCAG 2.5.3)").toBe(false);
    expect(cell(container, "2026-10-01").querySelector(".desk-cal__status")!.textContent).toBe(
      t("bn", "calendar.day.status.now", formatDate("bn", "2026-10-01"), t("bn", "calendar.count.papers.one", 1), t("bn", "calendar.count.follows.other", 0)),
    );
  });

  it("aDaysPapersAreNamedAndTheirUrgencyIsAShapeNotOnlyAColour", () => {
    const { container } = calendar();
    const now = cell(container, "2026-10-01").querySelector<HTMLElement>(".desk-cal__ev")!;
    expect(now.textContent).toBe(t("bn", "type.lab_report"));
    expect(now.classList.contains("desk-cal__ev--now")).toBe(true);
    expect(now.querySelector("[data-shape=octagon]"), "NOW draws its octagon").not.toBeNull();
    const plain = cell(container, "2026-10-31").querySelector<HTMLElement>(".desk-cal__ev")!;
    expect(plain.textContent).toBe(t("bn", "type.prescription"));
    expect(plain.className).not.toMatch(/desk-cal__ev--now|desk-cal__ev--week/);
    const week = render(<DeskCalendar {...props({ calendar: FORTY_FIVE })} />).container;
    const weekEv = cell(week, "2026-10-14").querySelectorAll(".desk-cal__ev");
    expect([...weekEv].map((e) => e.className).join(" "), "no urgency on 14 October").not.toMatch(/desk-cal__ev--now|desk-cal__ev--week/);
    const thisWeek = cell(week, "2026-10-02").querySelector<HTMLElement>(".desk-cal__ev--week")!;
    expect(thisWeek.querySelector("[data-shape=calendar-week]"), "THIS_WEEK draws its calendar").not.toBeNull();
  });

  it("todayIsFilledTheChosenDayIsCurrentAndADoctorsDayIsRinged", () => {
    const { container } = calendar({ asked: "2026-10-15" });
    expect(cell(container, "2026-10-20").classList.contains("desk-cal__day--today")).toBe(true);
    expect(cell(container, "2026-10-20").getAttribute("aria-current")).toBe("date");
    expect(cell(container, "2026-10-15").getAttribute("aria-current")).toBe("true");
    expect(container.querySelectorAll("td [aria-current=true]"), "one chosen day").toHaveLength(1);
    expect(cell(container, "2026-10-15").classList.contains("desk-cal__day--ring")).toBe(true);
    expect(cell(container, "2026-10-01").classList.contains("desk-cal__day--ring")).toBe(false);
    const visit = cell(container, "2026-10-15").querySelector<HTMLElement>(".desk-cal__ev--visit")!;
    expect(visit.textContent).toBe(t("bn", "desk.cal.visit"));
    // Fridays are drawn quieter, as the phone's and the prototype's are.
    expect(cell(container, "2026-10-02").classList.contains("desk-cal__day--fri")).toBe(true);
  });

  it("aCrowdedDayShowsThreeUrgentFirstAndCountsTheRest", () => {
    const { container } = calendar({ calendar: FORTY_FIVE });
    // 21 October: a prescription, a lab report, a NOW lab report, and a doctor's date.
    const day = cell(container, "2026-10-21");
    const evs = [...day.querySelectorAll<HTMLElement>(".desk-cal__ev")];
    expect(evs, "three shown").toHaveLength(3);
    expect(evs[0]!.classList.contains("desk-cal__ev--now"), "the NOW paper first").toBe(true);
    expect(evs[1]!.classList.contains("desk-cal__ev--visit"), "then the doctor's date").toBe(true);
    expect(day.querySelector(".desk-cal__more")!.textContent).toBe(`+${banglaDigits("1")}`);
    // The label still counts every paper: the rest is hidden from sight only.
    expect(day.querySelector(".desk-cal__status")!.textContent).toContain(banglaDigits("3"));
  });

  it("thePanelShowsTheChosenDaysPapersWithTheWayToTheirConversation", () => {
    const { container } = calendar({ asked: "2026-10-01" });
    const aside = panel(container);
    expect(aside.getAttribute("aria-label")).toBe(t("bn", "desk.cal.chosen"));
    expect(within(aside).getByRole("heading", { level: 2 }).textContent).toBe(formatDayMonth("bn", "2026-10-01"));
    const card = aside.querySelector<HTMLElement>(`[data-document="${NOW_LAB.document_id}"]`)!;
    expect(within(card).getByRole("heading", { level: 3 }).textContent).toBe(t("bn", "type.lab_report"));
    expect(card.textContent).toContain(NOW_LAB.facility!);
    expect(card.querySelector(".urgency-tag"), "the stored level, as the list draws it").not.toBeNull();
    expect(card.querySelector("img")!.getAttribute("src")).toBe(NOW_LAB.page_one.src);
    const go = within(card).getByRole("link", { name: t("bn", "desk.cal.open") });
    expect(go.getAttribute("href")).toBe(open(NOW_LAB.document_id));
    expect(aside.textContent).not.toContain(t("bn", "desk.cal.none"));
  });

  it("aDoctorsDayInThePanelShowsTheInstructionAsWrittenAndPromisesNothing", () => {
    const { container } = calendar({ asked: "2026-10-15" });
    const aside = panel(container);
    const card = aside.querySelector<HTMLElement>(".desk-cal__card--visit")!;
    expect(within(card).getByRole("heading", { level: 3 }).textContent).toBe(t("bn", "desk.cal.visit.title"));
    // The doctor's words, quoted under the title (desktop.html's `.ic small`), and the chip names the month alone.
    expect(card.querySelector(".desk-cal__card-sub")!.textContent).toBe(`\u201C${FOLLOW.instruction}\u201D`);
    expect(card.querySelector(".desk-cal__calchip-month")!.textContent).toBe(formatMonth("bn", "2026-10-15"));
    expect(card.querySelector("img")!.getAttribute("src"), "the doctor's own words, cropped").toBe(FOLLOW.crop.src);
    expect(within(card).getByRole("link", { name: t("bn", "desk.cal.paper") }).getAttribute("href")).toBe(open(FOLLOW.document_id));
    // desktop.html promises a WhatsApp reminder the evening before; the nudge engine sends one two days before, gated
    // and capped (NudgeRules.follow_up_due). The screen says nothing it cannot keep.
    expect(aside.textContent).not.toContain(REMINDER);
    expect(aside.textContent).not.toContain("WhatsApp");
  });

  it("aDayWithNothingSaysSo", () => {
    const { container } = calendar({ asked: "2026-10-02" });
    expect(panel(container).textContent).toContain(t("bn", "desk.cal.none"));
    expect(panel(container).querySelector(".desk-cal__card")).toBeNull();
  });

  it("theToolbarSaysTheMonthAndMovesByMonthAndBackToToday", () => {
    const { container, getByRole } = calendar();
    expect(getByRole("heading", { level: 1 }).textContent).toBe(formatMonthYear("bn", "2026-10-01"));
    expect(getByRole("link", { name: t("bn", "desk.cal.prev") }).getAttribute("href")).toBe(at({ month: "2026-09", view: "month" }));
    expect(getByRole("link", { name: t("bn", "desk.cal.next") }).getAttribute("href")).toBe(at({ month: "2026-11", view: "month" }));
    expect(getByRole("link", { name: t("bn", "desk.cal.today") }).getAttribute("href")).toBe(at({ month: "2026-10", day: "2026-10-20", view: "month" }));
    const views = within(container.querySelector<HTMLElement>(`[aria-label="${t("bn", "desk.cal.view")}"]`)!);
    expect(views.getByRole("link", { name: t("bn", "desk.cal.month") }).getAttribute("aria-current")).toBe("true");
    expect(views.getByRole("link", { name: t("bn", "desk.cal.list") }).getAttribute("aria-current")).toBeNull();
    expect(views.getByRole("link", { name: t("bn", "desk.cal.list") }).getAttribute("href")).toBe(at({ month: "2026-10", view: "list" }));
  });

  it("theListViewHoldsTheListAndNoMonthOrPanel", () => {
    const { container, getByRole, queryByRole } = calendar({ view: "list" });
    expect(container.querySelector("[data-slot=list]"), "the page's list").not.toBeNull();
    expect(container.querySelector("table"), "no month").toBeNull();
    expect(container.querySelector("aside"), "no day panel").toBeNull();
    expect(getByRole("heading", { level: 1 }).textContent).toBe(t("bn", "timeline.docs"));
    expect(queryByRole("link", { name: t("bn", "desk.cal.prev") }), "no month to move").toBeNull();
    const views = within(container.querySelector<HTMLElement>(`[aria-label="${t("bn", "desk.cal.view")}"]`)!);
    expect(views.getByRole("link", { name: t("bn", "desk.cal.list") }).getAttribute("aria-current")).toBe("true");
  });

  it("everyWordHasItsEnglish", () => {
    for (const lang of ["en"] as Lang[]) {
      const { container, getByRole } = calendar({ lang, asked: "2026-10-15" });
      expect(getByRole("link", { name: t(lang, "desk.cal.today") })).not.toBeNull();
      expect(container.textContent).toContain(t(lang, "desk.cal.visit.title"));
      expect(container.textContent).not.toMatch(/[\u0980-\u09FF]/);
    }
  });
});

function props(extra: Partial<DeskCalendarProps>): DeskCalendarProps {
  return {
    lang: "bn",
    view: "month",
    calendar: BUSY,
    today: "2026-10-20",
    asked: null,
    before: "2026-09",
    after: "2026-11",
    at,
    soft: false,
    open,
    ...extra,
  };
}

