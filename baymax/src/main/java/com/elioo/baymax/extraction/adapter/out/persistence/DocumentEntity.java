package com.elioo.baymax.extraction.adapter.out.persistence;

import com.elioo.baymax.config.BaymaxSchema;
import com.elioo.baymax.extraction.domain.Document;
import com.elioo.baymax.extraction.domain.FiledDay;
import com.elioo.baymax.extraction.domain.VerifiedItems;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.springframework.data.annotation.Id;
import org.springframework.data.annotation.ReadOnlyProperty;
import org.springframework.data.relational.core.mapping.Column;
import org.springframework.data.relational.core.mapping.Table;

import java.math.BigDecimal;
import java.time.Instant;
import java.time.LocalDate;
import java.util.UUID;

@Data
@NoArgsConstructor
@AllArgsConstructor
@Table(name = "document", schema = BaymaxSchema.NAME)
public class DocumentEntity {

    @Id
    private UUID id;
    @Column("patient_id")
    private UUID patientId;
    @Column("family_id")
    private UUID familyId;
    @Column("document_type")
    private String documentType;
    @Column("doc_date")
    private LocalDate docDate;
    private String facility;
    /** JSONB; Spring Data R2DBC maps it as String and Postgres casts on write. */
    @Column("extraction_json")
    private String extractionJson;
    @Column("confidence_overall")
    private Double confidenceOverall;
    private String status;
    @Column("status_reason")
    private String statusReason;
    @Column("model_final")
    private String modelFinal;
    @Column("cost_usd")
    private BigDecimal costUsd;
    @Column("page_count")
    private int pageCount;
    @Column("created_at")
    private Instant createdAt;
    @Column("updated_at")
    private Instant updatedAt;
    @Column("unverified_values")
    private int unverifiedValues;
    @Column("unverified_medicines")
    private int unverifiedMedicines;
    @Column("unverified_follow_up")
    private int unverifiedFollowUp;
    @Column("unverified_clinical_context")
    private int unverifiedClinicalContext;
    /** JSONB; the verified clinical lines, read together and never queried field by field. */
    @Column("clinical_context")
    private String clinicalContext;
    /** F5 (V20): the retake reason code, on NEEDS_RETAKE only. */
    @Column("status_reason_code")
    private String statusReasonCode;
    /** D3 (V21): the web press that made this document. Read here, written only by {@code createOnce}'s SQL. */
    @Column("upload_key")
    @ReadOnlyProperty
    private String uploadKey;
    /** D2: the model marked the printed date uncertain; written by {@code finish}, false when it said nothing. */
    @Column("doc_date_uncertain")
    private boolean docDateUncertain;
    /** D2: the day the paper is filed under, generated by Postgres; read here, never written. */
    @Column("timeline_date")
    @ReadOnlyProperty
    private LocalDate timelineDate;
    /** D2: generated with {@code timeline_date}: true when it is the Dhaka upload day, not the printed date. */
    @Column("timeline_date_is_upload_day")
    @ReadOnlyProperty
    private Boolean timelineDateIsUploadDay;
    /** D2: generated with {@code timeline_date}: the model's mark, only where the paper is filed under its printed date. */
    @Column("timeline_date_uncertain")
    @ReadOnlyProperty
    private Boolean timelineDateUncertain;

    static DocumentEntity from(Document d) {
        return new DocumentEntity(d.id(), d.patientId(), d.familyId(), d.documentType(), d.docDate(),
                d.facility(), d.extractionJson(), d.confidenceOverall(), d.status().name(), d.statusReason(),
                d.modelFinal(), d.costUsd(), d.pageCount(), d.createdAt(), d.updatedAt(),
                d.unverified().values(), d.unverified().medicines(), d.unverified().followUp(),
                d.unverified().clinicalContext(), d.clinicalContextJson(), d.statusReasonCode(), null,
                d.docDateUncertain(), null, null, null);
    }

    /**
     * The generated filing columns as one {@link FiledDay}, or null when this entity was not read from a row (an insert's
     * return carries only what Java sent). A row always has {@code timeline_date}, since {@code created_at} is NOT NULL.
     */
    private FiledDay filed() {
        return timelineDate == null ? null
                : new FiledDay(timelineDate, Boolean.TRUE.equals(timelineDateIsUploadDay), Boolean.TRUE.equals(timelineDateUncertain));
    }

    Document toRecord() {
        return new Document(id, patientId, familyId, documentType, docDate, facility, extractionJson,
                confidenceOverall, Document.Status.fromDbValue(status), statusReason, modelFinal, costUsd,
                pageCount, createdAt, updatedAt,
                new VerifiedItems.Unverified(unverifiedValues, unverifiedMedicines, unverifiedFollowUp,
                        unverifiedClinicalContext),
                clinicalContext, statusReasonCode, docDateUncertain, filed());
    }
}
