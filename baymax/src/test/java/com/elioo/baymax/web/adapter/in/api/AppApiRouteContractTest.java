/**
 * Plan B1 step 5, derived from the running module rather than written down: every {@link RouterFunction} bean of a real
 * Baymax context is walked ({@link RouteWalk}), and
 * <ul>
 *   <li>every route under {@code /app/api}, under every method it answers, refuses a request with no session with 401
 *       {@code {"reason":"UNAUTHENTICATED"}}, no {@code Location} and {@code Cache-Control: no-store}, through the
 *       context's own handler mapping; the list is checked non-empty first. The routes in {@link AppApiGuard#OPEN}
 *       (sign-in) need no session and are skipped there; instead each one, with no session, still refuses every broken
 *       CSRF rule, a missing {@code Origin} included;</li>
 *   <li>every one of those under a mutating method (POST, PUT, PATCH, DELETE) refuses a live session that omits
 *       {@code X-Medioo} with 403 {@code MISSING_HEADER}, and one from another {@code Origin} with 403
 *       {@code FORBIDDEN_ORIGIN} — derived the same way, so a DELETE route added later is swept without anyone
 *       remembering to add it;</li>
 *   <li>with an HTML-style catch-all router added to the context ({@code /app/{*rest}} behind a 303 to sign-in, the
 *       shape a future HTML route takes), every {@code /app/api} route still answers the 401: this is what holds
 *       {@link AppApiRouter}'s precedence, since no HTML route of today matches {@code /app/api/**};</li>
 *   <li>every {@code /app/**} and {@code /baymax/**} route of the Baymax module, method and pattern, sorted, is written
 *       to {@code build/route-contract/app-routes.txt} and must equal the committed {@code docs/infra/app-routes.txt}.
 *       URLs already sent over WhatsApp must keep working forever; a route that disappears or changes shape fails here.
 *       That no medscribe-ai router publishes a path under {@code /app} or {@code /baymax} is asserted in medscribe-ai
 *       ({@code AppApiDeployableTest}), against the same snapshot.</li>
 * </ul>
 */
@Testcontainers
class AppApiRouteContractTest {

    @Container
    static final PostgreSQLContainer<?> POSTGRES = new PostgreSQLContainer<>("postgres:17-alpine");

    static final Path SNAPSHOT = Path.of("../docs/infra/app-routes.txt");
    static final Path WRITTEN = Path.of("build/route-contract/app-routes.txt");
    static final String HEADER = """
            # Every /app/** and /baymax/** route the Baymax module serves: METHOD PATTERN, sorted ("*" = any method).
            # Generated by baymax AppApiRouteContractTest from the running routers; never edited by hand. That no other
            # router of the deployable serves a path under /app or /baymax is asserted by medscribe-ai AppApiDeployableTest.
            # URLs sent over WhatsApp depend on these. A change here needs PO sign-off in the PR.
            """;

    /** The legacy URLs the rebuild plan's Global Constraints promise forever; the snapshot must keep each one. */
    static final List<String> LEGACY = List.of("GET /app", "GET /app/", "GET /app/documents/{id}", "GET /app/documents/{id}/all",
            "GET /app/documents/{id}/values/{obs}", "GET /app/patients/{id}", "GET /app/nudges/opt-out", "GET /baymax/{*rest}");

    /** What HTTP calls a mutation; the guard's own set is what is under test, so it is not read from there. */
    static final Set<HttpMethod> MUTATING = Set.of(HttpMethod.POST, HttpMethod.PUT, HttpMethod.PATCH, HttpMethod.DELETE);

    @Test
    void everyApiRouteAnswersAVisitorWithoutASession401AndTheRouteTableMatchesTheSnapshot() {
        AppApiContext.runner(POSTGRES).run(context -> {
            List<RouteWalk.Route> all = routes(context);
            List<String> leaks = sweepWithoutSession(context, api(all));
            assertThat(leaks).as("/app/api routes that answered a visitor without a session with something other than the 401 reason").isEmpty();

            String table = HEADER + all.stream().filter(r -> isAppRoute(r.pattern())).map(RouteWalk.Route::line)
                    .collect(Collectors.toCollection(TreeSet::new)).stream().collect(Collectors.joining("\n", "", "\n"));
            Files.createDirectories(WRITTEN.getParent());
            Files.writeString(WRITTEN, table, StandardCharsets.UTF_8);
            assertThat(table.lines().toList()).as("the generated table keeps every legacy WhatsApp URL").containsAll(LEGACY);
            assertThat(Files.exists(SNAPSHOT)).as("docs/infra/app-routes.txt is committed (copy it from " + WRITTEN + " after review)").isTrue();
            assertThat(table)
                    .as("a legacy /app route changed — WhatsApp links depend on it; update the snapshot only with PO sign-off"
                            + " (generated: baymax/" + WRITTEN + ")")
                    .isEqualTo(Files.readString(SNAPSHOT, StandardCharsets.UTF_8));
        });
    }

    /** CSRF, derived from the routes: every mutating (method, route) pair refuses each broken rule with its own reason. */
    @Test
    void everyMutatingApiRouteRefusesAMissingHeaderAndAForeignOriginWithItsReason() {
        AppApiContext.runner(POSTGRES).run(context -> {
            FamilyAccount family = AppApiContext.family(context, "+8801700000401", "Tanvir");
            String token = AppApiContext.session(context, family.id());
            WebTestClient client = WebTestClient.bindToApplicationContext(context).build();

            List<String> swept = new ArrayList<>();
            List<String> leaks = new ArrayList<>();
            for (RouteWalk.Route route : api(routes(context))) {
                for (HttpMethod method : methods(route)) {
                    if (!MUTATING.contains(method)) {
                        continue;
                    }
                    String uri = concrete(route.pattern());
                    swept.add(method + " " + route.pattern());
                    expect(leaks, method + " " + uri + " without X-Medioo", 403, "{\"reason\":\"MISSING_HEADER\"}",
                            client.method(method).uri(uri).cookie("baymax_session", token)
                                    .contentType(MediaType.APPLICATION_JSON).bodyValue("{}")
                                    .exchange().expectBody().returnResult());
                    expect(leaks, method + " " + uri + " from another Origin", 403, "{\"reason\":\"FORBIDDEN_ORIGIN\"}",
                            client.method(method).uri(uri).cookie("baymax_session", token).header("X-Medioo", "1")
                                    .header("Origin", "https://evil.example")
                                    .contentType(MediaType.APPLICATION_JSON).bodyValue("{}")
                                    .exchange().expectBody().returnResult());
                }
            }
            assertThat(swept).as("mutating (method, route) pairs read from the routers; none would make this sweep vacuous").isNotEmpty();
            assertThat(swept).as("the catch-all is swept under every mutating method")
                    .contains("POST /app/api/**", "PUT /app/api/**", "PATCH /app/api/**", "DELETE /app/api/**");
            assertThat(leaks).as("mutating /app/api requests that were not refused for the CSRF rule they broke").isEmpty();
        });
    }

    /**
     * The sign-in pair needs no session, so CSRF is all that stands in front of it, and a missing {@code Origin} is
     * refused there (a server-side caller must not reach a route that sends WhatsApp messages). Derived from the walked
     * routes: a route added to {@link AppApiGuard#OPEN} later is swept here without anyone remembering to add it.
     */
    @Test
    void everyOpenRouteStillRefusesCsrfWithoutASession() {
        AppApiContext.runner(POSTGRES).run(context -> {
            WebTestClient client = WebTestClient.bindToApplicationContext(context).build();
            List<String> swept = new ArrayList<>();
            List<String> leaks = new ArrayList<>();
            for (RouteWalk.Route route : api(routes(context))) {
                if (!AppApiGuard.OPEN.contains(route.pattern())) {
                    continue;
                }
                for (HttpMethod method : methods(route)) {
                    String uri = concrete(route.pattern());
                    swept.add(method + " " + route.pattern());
                    expect(leaks, method + " " + uri + " without X-Medioo", 403, "{\"reason\":\"MISSING_HEADER\"}",
                            client.method(method).uri(uri).header("Origin", AppApiContext.ORIGIN)
                                    .contentType(MediaType.APPLICATION_JSON).bodyValue("{}")
                                    .exchange().expectBody().returnResult());
                    expect(leaks, method + " " + uri + " from another Origin", 403, "{\"reason\":\"FORBIDDEN_ORIGIN\"}",
                            client.method(method).uri(uri).header("X-Medioo", "1").header("Origin", "https://evil.example")
                                    .contentType(MediaType.APPLICATION_JSON).bodyValue("{}")
                                    .exchange().expectBody().returnResult());
                    expect(leaks, method + " " + uri + " with no Origin at all", 403, "{\"reason\":\"FORBIDDEN_ORIGIN\"}",
                            client.method(method).uri(uri).header("X-Medioo", "1")
                                    .contentType(MediaType.APPLICATION_JSON).bodyValue("{}")
                                    .exchange().expectBody().returnResult());
                }
            }
            assertThat(swept).as("open (method, route) pairs read from the routers; none would make this sweep vacuous").isNotEmpty();
            assertThat(leaks).as("open /app/api requests without a session that were not refused for the CSRF rule they broke").isEmpty();
        });
    }

    /** {@link AppApiGuard#OPEN} names routes the routers publish, and only mutations: a GET is never sessionless here. */
    @Test
    void theOpenRoutesAreRoutesThatExistAndAreMutations() {
        AppApiContext.runner(POSTGRES).run(context -> {
            List<RouteWalk.Route> api = api(routes(context));
            assertThat(AppApiGuard.OPEN).as("the open set").isNotEmpty();
            assertThat(api.stream().map(RouteWalk.Route::pattern).toList()).as("patterns the routers publish")
                    .containsAll(AppApiGuard.OPEN);
            assertThat(api.stream().filter(r -> AppApiGuard.OPEN.contains(r.pattern())).map(RouteWalk.Route::method).toList())
                    .as("the methods of the open routes").isNotEmpty().allMatch("POST"::equals);
        });
    }

    /**
     * The precedence claim, made falsifiable: an HTML-style catch-all over {@code /app/{*rest}} that answers 303 to
     * sign-in, registered at default order, must not see a single {@code /app/api} request.
     */
    @Test
    void anHtmlCatchAllUnderAppNeverCapturesAnApiRoute() {
        AppApiContext.runner(POSTGRES).withUserConfiguration(HtmlCatchAll.class).run(context -> {
            List<String> leaks = sweepWithoutSession(context, api(routes(context)));
            assertThat(leaks).as("/app/api routes the HTML catch-all captured (its 303) instead of the 401 reason").isEmpty();
            // the catch-all is live: a path outside /app/api is its
            WebTestClient.bindToApplicationContext(context).build().get().uri("/app/anything").exchange()
                    .expectStatus().isSeeOther();
        });
    }

    /**
     * A future HTML route shaped like requireSession's refusal: everything under /app, 303 to sign-in. Deliberately not
     * a {@code @Configuration}: {@code BaymaxAutoConfiguration} component-scans {@code com.elioo.baymax}, test classes
     * included, and would put this router into every other test's context.
     */
    static class HtmlCatchAll {
        @Bean
        RouterFunction<ServerResponse> htmlCatchAll() {
            return RouterFunctions.route(RequestPredicates.path("/app/{*rest}"),
                    request -> ServerResponse.seeOther(URI.create("/app/")).build());
        }
    }

    private static List<String> sweepWithoutSession(ApplicationContext context, List<RouteWalk.Route> api) {
        assertThat(api).as("the /app/api routes read from the routers; none would make the 401 sweep vacuous").isNotEmpty();
        WebTestClient client = WebTestClient.bindToApplicationContext(context).build();
        List<String> leaks = new ArrayList<>();
        for (RouteWalk.Route route : api) {
            if (AppApiGuard.OPEN.contains(route.pattern())) {
                continue;   // needs no session; everyOpenRouteStillRefusesCsrfWithoutASession sweeps it instead
            }
            for (HttpMethod method : methods(route)) {
                String uri = concrete(route.pattern());
                expect(leaks, method + " " + uri, 401, "{\"reason\":\"UNAUTHENTICATED\"}",
                        client.method(method).uri(uri).exchange().expectBody().returnResult());
            }
        }
        return leaks;
    }

    private static void expect(List<String> leaks, String what, int status, String body, EntityExchangeResult<byte[]> r) {
        String got = r.getResponseBody() == null ? "" : new String(r.getResponseBody(), StandardCharsets.UTF_8);
        String cache = r.getResponseHeaders().getCacheControl();
        if (r.getStatus().value() != status || !got.equals(body) || r.getResponseHeaders().getLocation() != null
                || !"no-store".equals(cache)) {
            leaks.add(what + " answered " + r.getStatus().value() + " " + got + " Location=" + r.getResponseHeaders().getLocation()
                    + " Cache-Control=" + cache);
        }
    }

    private static List<RouteWalk.Route> api(List<RouteWalk.Route> all) {
        return all.stream().filter(r -> r.pattern().startsWith(AppApiRouter.BASE + "/")).toList();
    }

    static boolean isAppRoute(String pattern) {
        return pattern.equals("/app") || pattern.startsWith("/app/") || pattern.equals("/baymax") || pattern.startsWith("/baymax/");
    }

    /** Every route of every router bean in the context. */
    static List<RouteWalk.Route> routes(ApplicationContext context) {
        List<RouteWalk.Route> all = new ArrayList<>();
        for (RouterFunction<?> router : context.getBeansOfType(RouterFunction.class).values()) {
            all.addAll(RouteWalk.of(router));
        }
        assertThat(all).as("router beans in the context").isNotEmpty();
        return all;
    }

    /** {@code *} is every method a browser would send; otherwise the route's own. */
    static List<HttpMethod> methods(RouteWalk.Route route) {
        return route.method().equals("*")
                ? List.of(HttpMethod.GET, HttpMethod.POST, HttpMethod.PUT, HttpMethod.PATCH, HttpMethod.DELETE)
                : List.of(HttpMethod.valueOf(route.method()));
    }

    /** A URI the pattern matches: each {@code {var}} a fresh UUID, {@code **} one segment. */
    static String concrete(String pattern) {
        return pattern.replaceAll("\\{\\*?[^}]+}", UUID.randomUUID().toString()).replace("**", "x");
    }
}
