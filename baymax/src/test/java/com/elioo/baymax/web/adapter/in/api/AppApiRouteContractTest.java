package com.elioo.baymax.web.adapter.in.api;

import org.junit.jupiter.api.Test;
import org.springframework.context.ApplicationContext;
import org.springframework.http.HttpMethod;
import org.springframework.test.web.reactive.server.EntityExchangeResult;
import org.springframework.test.web.reactive.server.WebTestClient;
import org.springframework.web.reactive.function.server.RouterFunction;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.TreeSet;
import java.util.UUID;
import java.util.stream.Collectors;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Plan B1 step 5, derived from the running module rather than written down: every {@link RouterFunction} bean of a real
 * Baymax context is walked ({@link RouteWalk}), and
 * <ul>
 *   <li>every route under {@code /app/api} answers a request with no session 401 {@code {"reason":"UNAUTHENTICATED"}}
 *       through the context's own handler mapping — so the ordering of the routers is what is under test, and an API
 *       route that fell into the HTML router's 303 fails here — and the list is checked non-empty first;</li>
 *   <li>every {@code /app/**} and {@code /baymax/**} route, method and pattern, sorted, is written to
 *       {@code build/route-contract/app-routes.txt} and must equal the committed {@code docs/infra/app-routes.txt}. URLs
 *       already sent over WhatsApp must keep working forever; a route that disappears or changes shape fails here.</li>
 * </ul>
 */
@Testcontainers
class AppApiRouteContractTest {

    @Container
    static final PostgreSQLContainer<?> POSTGRES = new PostgreSQLContainer<>("postgres:17-alpine");

    static final Path SNAPSHOT = Path.of("../docs/infra/app-routes.txt");
    static final Path WRITTEN = Path.of("build/route-contract/app-routes.txt");
    static final String HEADER = """
            # Every /app/** and /baymax/** route the Java app serves: METHOD PATTERN, sorted ("*" = any method).
            # Generated by baymax AppApiRouteContractTest from the running routers; never edited by hand.
            # URLs sent over WhatsApp depend on these. A change here needs PO sign-off in the PR.
            """;

    /** The legacy URLs the rebuild plan's Global Constraints promise forever; the snapshot must keep each one. */
    static final List<String> LEGACY = List.of("GET /app", "GET /app/", "GET /app/documents/{id}", "GET /app/documents/{id}/all",
            "GET /app/documents/{id}/values/{obs}", "GET /app/patients/{id}", "GET /app/nudges/opt-out", "GET /baymax/{*rest}");

    @Test
    void everyApiRouteAnswersAVisitorWithoutASession401AndTheRouteTableMatchesTheSnapshot() {
        AppApiContext.runner(POSTGRES).run(context -> {
            List<RouteWalk.Route> all = routes(context);
            List<RouteWalk.Route> api = all.stream().filter(r -> r.pattern().startsWith(AppApiRouter.BASE + "/")).toList();
            assertThat(api).as("the /app/api routes read from the routers; none would make the 401 sweep vacuous").isNotEmpty();

            WebTestClient client = WebTestClient.bindToApplicationContext(context).build();
            List<String> leaks = new ArrayList<>();
            for (RouteWalk.Route route : api) {
                for (HttpMethod method : methods(route)) {
                    String uri = concrete(route.pattern());
                    EntityExchangeResult<byte[]> r = client.method(method).uri(uri).exchange().expectBody().returnResult();
                    String body = r.getResponseBody() == null ? "" : new String(r.getResponseBody(), StandardCharsets.UTF_8);
                    if (r.getStatus().value() != 401 || !body.equals("{\"reason\":\"UNAUTHENTICATED\"}")
                            || r.getResponseHeaders().getLocation() != null) {
                        leaks.add(method + " " + uri + " answered " + r.getStatus().value() + " " + body
                                + " Location=" + r.getResponseHeaders().getLocation());
                    }
                }
            }
            assertThat(leaks).as("/app/api routes that answered a visitor without a session with something other than the 401 reason").isEmpty();

            String table = HEADER + all.stream().filter(r -> isAppRoute(r.pattern())).map(RouteWalk.Route::line)
                    .collect(Collectors.toCollection(TreeSet::new)).stream().collect(Collectors.joining("\n", "", "\n"));
            Files.createDirectories(WRITTEN.getParent());
            Files.writeString(WRITTEN, table, StandardCharsets.UTF_8);
            assertThat(table.lines().toList()).as("the generated table keeps every legacy WhatsApp URL").containsAll(LEGACY);
            assertThat(Files.exists(SNAPSHOT)).as("docs/infra/app-routes.txt is committed (copy it from " + WRITTEN + " after review)").isTrue();
            assertThat(table)
                    .as("a legacy /app route changed — WhatsApp links depend on it; update the snapshot only with PO sign-off"
                            + " (generated: baymax/" + WRITTEN + ")")
                    .isEqualTo(Files.readString(SNAPSHOT, StandardCharsets.UTF_8));
        });
    }

    static boolean isAppRoute(String pattern) {
        return pattern.equals("/app") || pattern.startsWith("/app/") || pattern.equals("/baymax") || pattern.startsWith("/baymax/");
    }

    /** Every route of every router bean in the context. */
    static List<RouteWalk.Route> routes(ApplicationContext context) {
        List<RouteWalk.Route> all = new ArrayList<>();
        for (RouterFunction<?> router : context.getBeansOfType(RouterFunction.class).values()) {
            all.addAll(RouteWalk.of(router));
        }
        assertThat(all).as("router beans in the context").isNotEmpty();
        return all;
    }

    /** {@code *} is every method a browser would send; otherwise the route's own. */
    static List<HttpMethod> methods(RouteWalk.Route route) {
        return route.method().equals("*")
                ? List.of(HttpMethod.GET, HttpMethod.POST, HttpMethod.PUT, HttpMethod.PATCH, HttpMethod.DELETE)
                : List.of(HttpMethod.valueOf(route.method()));
    }

    /** A URI the pattern matches: each {@code {var}} a fresh UUID, {@code **} one segment. */
    static String concrete(String pattern) {
        return pattern.replaceAll("\\{\\*?[^}]+}", UUID.randomUUID().toString()).replace("**", "x");
    }
}
